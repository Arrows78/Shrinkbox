#!/usr/bin/env python3
"""Builds Resources/<lang>.lproj/Localizable.strings from scripts/data/translations.tsv (key, es, de).

French and English are hand-maintained; this file holds the other languages in one table so a missing
key or a changed placeholder is caught in one place. Run it after editing the table.
"""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
fr = (root / "Resources/fr.lproj/Localizable.strings").read_text()
keys = [k for k, _ in re.findall(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', fr, re.M)]
LANGS = ["es", "de"]
rows = {}
for n, line in enumerate((root / "scripts/data/translations.tsv").read_text().splitlines(), 1):
    if not line.strip(): continue
    parts = line.split("\t")
    if len(parts) != len(LANGS) + 1: sys.exit(f"translations.tsv:{n}: expected {len(LANGS) + 1} columns, got {len(parts)}")
    if parts[0] in rows: sys.exit(f"translations.tsv:{n}: duplicate key {parts[0]!r}")
    rows[parts[0]] = parts[1:]
missing = [k for k in keys if k not in rows]; extra = [k for k in rows if k not in keys]
if missing or extra: sys.exit(f"missing: {missing}\nunknown: {extra}")
ph = lambda s: sorted(re.findall(r"%(?:lld|d|@|%)", s))
for i, lang in enumerate(LANGS):
    out = [f"/* Shrinkbox, {lang}. Generated by scripts/gen_lproj.py from scripts/data/translations.tsv: do not edit by hand. */\n"]
    for k in keys:
        v = rows[k][i]
        if ph(v) != ph(k): sys.exit(f"{lang}: placeholders differ for {k!r}: {v!r}")
        esc = lambda t: t.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'"{esc(k)}" = "{esc(v)}";')
    d = root / f"Resources/{lang}.lproj"; d.mkdir(exist_ok=True)
    (d / "Localizable.strings").write_text("\n".join(out) + "\n")
    print(f"{lang}: {len(keys)} strings")
